package week1;

public class TracingExample {
    static void main() {
        double radius = 10;
        double pi = 3.14;
        double area;

        System.out.println("Radius is "+radius);
        area = pi * radius * radius;
        double circumference = pi * 2 * radius;

        System.out.println("Area is "+area);
        System.out.println("Circumference is "+circumference);
    }
}
